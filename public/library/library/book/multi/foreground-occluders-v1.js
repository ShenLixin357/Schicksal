export function createSceneMask([x,y,width,height],draw){
  const image=Object.assign(document.createElement('canvas'),{width,height});
  const context=image.getContext('2d');
  context.translate(-x,-y);
  context.fillStyle='#000';
  draw(context);
  return {image,x,y};
}

function drawArmillary(context){
  context.fill(armillarySupports);
  context.fill(hub);
  context.strokeStyle='#000';
  context.lineWidth=2.5;
  context.lineCap='round';
  context.lineJoin='round';
  context.stroke(fineBrass);
}

export function createArmillaryMask(){
  return createSceneMask([638,548,94,114],drawArmillary);
}

export function createForegroundMask(includeDeskProps,{deskCandle=true}={}){
  return createSceneMask([510,430,646,232],context=>{
    context.fill(floatingBooks);
    if(includeDeskProps){
      context.fill(bouquet);
      drawArmillary(context);
      if(deskCandle)context.fill(earlierDeskCandle);
    }
  });
}
